"""夜街：L0 夜空+远山 / L1 远处楼群与树 / L2 临街店铺（含晾衣绳、背后那根路灯杆、人行道和路面）/ L3 店前三根路灯杆。
招牌字（小卖部、录像厅、运动）抹成空白色块。"""
from split_util import *
a = load('5_night_street.png'); H, W, _ = a.shape
erase_watermark(a)
erase(a, (354, 596, 642, 680), size=None, t=60, grow=3)      # 小卖部
erase(a, (1372, 573, 1683, 652), size=None, t=60, grow=3)    # 录像厅
erase(a, (0, 606, 232, 686), size=None, t=14, grow=4, blur=3)          # 左侧"运动"
erase(a, (1322, 742, 1352, 806), size=None, t=45, grow=1)    # 录像厅门边小牌
yy = np.arange(H)[:, None] * np.ones((1, W))
lum = a.mean(2); sat = a.max(2) - a.min(2)
# L1 远处楼群（暗、虚，天际线粗略即可）
far = poly(a.shape, [(0, 335), (300, 335), (300, 398), (520, 398), (520, 415), (960, 415), (960, 405), (1400, 405),
                     (1400, 298), (1600, 298), (1600, 360), (1650, 360), (1650, 300), (W, 300), (W, 700), (0, 700)])
# L2 临街店铺
front = poly(a.shape, [(0, 401), (262, 401), (300, 440), (300, 640), (340, 640), (340, 581), (656, 581), (656, 612),
                       (712, 640), (712, 688), (1325, 688), (1325, 637), (1358, 637), (1358, 559), (1648, 559), (1648, 424),
                       (1730, 372), (W, 372), (W, H), (0, H)])
bush = poly(a.shape, [(758, 692), (758, 662), (775, 665), (782, 648), (795, 660), (805, 652), (815, 655), (828, 650), (835, 660),
                      (860, 652), (885, 650), (905, 655), (925, 665), (952, 692)])
box = poly(a.shape, [(905, 512), (1392, 512), (1392, 676), (905, 676)])
cloth = box & ((lum > 72) | (sat > 85))
lab, n = nd.label(cloth); sz = nd.sum(cloth, lab, range(1, n + 1))
cloth = np.isin(lab, 1 + np.where(sz >= 40)[0]); cloth = nd.binary_fill_holes(nd.binary_closing(cloth, iterations=2))
pole3 = poly(a.shape, [(1377, 354), (1399, 354), (1399, 690), (1377, 690)],
             [(1266, 370), (1285, 362), (1305, 364), (1320, 373), (1312, 386), (1285, 387), (1268, 378)],
             [(1310, 371), (1420, 382), (1420, 393), (1310, 383)], [(1325, 381), (1380, 404), (1380, 420), (1325, 391)],
             [(1292, 530), (1307, 530), (1307, 690), (1292, 690)])
front |= bush | cloth | pole3
# L3 店前路灯杆
poles = poly(a.shape,
             [(302, 324), (324, 324), (314, 680), (315, 956), (278, 956), (286, 765), (290, 680)],
             [(280, 364), (352, 366), (352, 375), (280, 373)],
             [(318, 372), (350, 358), (362, 347), (385, 340), (406, 344), (400, 364), (372, 372), (352, 374), (326, 398)],
             [(734, 331), (759, 331), (762, 956), (730, 956)],
             [(704, 362), (762, 365), (762, 375), (704, 372)],
             [(755, 366), (770, 348), (800, 342), (814, 350), (802, 366), (770, 373)],
             [(1729, 174), (1764, 174), (1771, 680), (1776, 858), (1786, 858), (1786, 956), (1739, 956), (1741, 680)],
             [(1528, 204), (1545, 194), (1592, 194), (1622, 210), (1616, 229), (1590, 231), (1540, 222)],
             [(1615, 214), (1792, 228), (1792, 251), (1615, 233)],
             [(1640, 224), (1700, 249), (1738, 300), (1731, 312), (1690, 262), (1640, 236)])
poles = nd.binary_dilation(poles, iterations=3)   # 杆子边缘有亮边，框外扩 3px
build('night_street', a, [far, front, poles], ['far', 'mid', 'mid', 'near'], 985, 'outdoor',
      '地面线 y=985 是人行道路沿；L2 含人行道和路面（y>985 是马路，带两摊积水倒影），场景若自己铺地面可盖住。'
      '招牌字已抹成空白色块；远处楼群在夜色里很暗，天际线是粗框。')

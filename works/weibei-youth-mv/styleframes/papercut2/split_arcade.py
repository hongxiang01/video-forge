build('arcade', a, [cabs | stools, fans, fg], ['far', 'mid', 'mid', 'near'], 1000, 'indoor',
      '室内：floor_y=1000 是街机底座/圆凳腿落地一带，人物站在街机前的地砖上。L3 左下角虚焦杂物占画面左下约 300x400，'
      '会挡住站到最左边的人；右侧塑料门帘留在 L0。')

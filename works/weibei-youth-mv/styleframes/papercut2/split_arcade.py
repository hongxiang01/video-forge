patch(a, (1550, 606, 1638, 643))    # 右墙海报底部字
yy = np.arange(H)[:, None] * np.ones((1, W))
lum = a.mean(2)
cabs = poly(a.shape,
            [(410, 504), (684, 504), (684, 560), (655, 600), (625, 760), (612, 800), (641, 830), (641, 987), (369, 987),
             (367, 822), (339, 812), (339, 768), (385, 750), (430, 590), (410, 570)],
            [(688, 497), (943, 497), (943, 560), (931, 760), (933, 820), (931, 987), (661, 987), (659, 822), (644, 802),
             (644, 758), (680, 740), (700, 600), (688, 560)],
            [(955, 502), (1196, 502), (1196, 580), (1216, 760), (1216, 987), (949, 987), (949, 760)],
            [(1211, 496), (1459, 496), (1459, 575), (1513, 745), (1513, 823), (1498, 823), (1498, 989), (1221, 989),
             (1221, 823), (1211, 800)],
            [(1554, 726), (1641, 726), (1641, 769), (1696, 789), (1696, 826), (1689, 987), (1534, 987), (1529, 821),
             (1526, 769), (1554, 769)])
stools = poly(a.shape, *[[(x0, 878), (x1, 878), (x1, 922), (x1 + 10, 1024), (x0 - 8, 1024), (x0 + 2, 922)]
                         for x0, x1 in [(393, 521), (706, 832), (1009, 1134), (1296, 1426)]])
# 吊扇：深色天花板上的浅色纸片
box = poly(a.shape, [(292, 0), (752, 0), (752, 252), (292, 252)], [(822, 60), (1242, 60), (1242, 252), (822, 252)],
           [(1252, 0), (1758, 0), (1758, 236), (1252, 236)])
gb = a[..., 1] - a[..., 2]; sr = (a.max(2) - a.min(2)) / (a.max(2) + 1)

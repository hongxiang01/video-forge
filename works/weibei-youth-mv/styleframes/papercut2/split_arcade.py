fans = nd.binary_opening(nd.binary_fill_holes(nd.binary_closing(fans, iterations=2)), iterations=1)
lab, n = nd.label(fans); sz = nd.sum(fans, lab, range(1, n + 1)); fans = np.isin(lab, 1 + np.where(sz > 300)[0])
fans |= poly(a.shape, [(536, 0), (553, 0), (553, 145), (536, 145)], [(1016, 74), (1036, 74), (1036, 168), (1016, 168)],
             [(1501, 0), (1519, 0), (1519, 80), (1501, 80)], [(1489, 76), (1533, 76), (1533, 108), (1489, 108)])
